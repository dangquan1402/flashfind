#!/usr/bin/env bash
# Code-projects benchmark: `flashfind code` (discovered repos, gitignore +
# junk excluded) vs a plain whole-tree flashfind index of the same folder.
#   bench/run-code.sh [REPOS=200] [SEED=7]
# Env: FLASHFIND_BENCH_DIR (default ~/dev/flashfind-bench), REPEAT (default 5).
set -euo pipefail
REPOS=${1:-200}
SEED=${2:-7}
REPEAT=${REPEAT:-5}
REPO="$(cd "$(dirname "$0")/.." && pwd)"
BENCH=${FLASHFIND_BENCH_DIR:-$HOME/dev/flashfind-bench}
TREE="$BENCH/repos-$REPOS-$SEED.noindex"
Q="$BENCH/repos-queries-$REPOS-$SEED.jsonl"
OUT="$REPO/bench/out"
mkdir -p "$OUT" "$BENCH"
(cd "$REPO" && cargo build --release -q -p flashfind-cli)
FF="$REPO/target/release/flashfind"
if [ ! -f "$TREE.complete" ]; then
  case "$TREE" in "$BENCH"/repos-*) rm -rf "$TREE" ;; esac
  "$FF" gen-repos --root "$TREE" --repos "$REPOS" --seed "$SEED" --queries "$Q"
  touch "$TREE.complete"
fi
"$FF" bench-code --root "$TREE" --queries "$Q" --repeat 1 --out /dev/null >/dev/null   # warm-up
LOAD=$(uptime | sed 's/.*load averages*: //')
"$FF" bench-code --root "$TREE" --queries "$Q" --repeat "$REPEAT" --out "$OUT/code.json" --md "$OUT/code.md" >/dev/null
{
  echo "# Code-projects benchmark"
  echo
  echo "Synthetic home: $REPOS git repos (Rust, TS, JS, Python, Swift, Go) with sources plus realistic junk"
  echo "(\`node_modules\`, \`target\`, \`.venv\`, \`.build\`/\`DerivedData\`, \`.git\` objects, gitignored logs) and"
  echo "20 k non-project files under \`Library/\`. Seed $SEED. Generated by \`flashfind gen-repos\`; run with"
  echo "\`bench/run-code.sh\`. Both columns use the same flashfind engine, so this measures what the"
  echo "code index removes, not engine speed. Latency is per query (top 10), $REPEAT passes."
  echo
  if command -v sw_vers >/dev/null; then
    echo "Machine: macOS $(sw_vers -productVersion), $(sysctl -n machdep.cpu.brand_string), $(sysctl -n hw.ncpu) cores; load average: $LOAD"
  else
    echo "Machine: $(uname -srm), $(nproc) cores; load average: $LOAD"
  fi
  echo "flashfind $(git -C "$REPO" rev-parse --short HEAD)"
  echo
  cat "$OUT/code.md"
  echo
  echo "Notes: *name* = bare file stem (many stems repeat across repos, so hit@1 is capped by"
  echo "ambiguity; hit@10 shows whether the file is on the first page); *typo* = one substituted"
  echo "letter; *repo_scoped* = \`repo:<name> <stem>\` (the plain index has no repo filter and gets"
  echo "the bare stem); *folder_name* = \`<parent folder> <stem>\`. \"Junk\" = results under"
  echo "node_modules, target, .git, .venv, .build, DerivedData, Library, dist, bin, logs, or *.log."
} > "$REPO/bench/CODE_RESULTS.md"
cat "$REPO/bench/CODE_RESULTS.md"
