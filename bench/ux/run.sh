#!/usr/bin/env bash
# UX replay eval: right-file-first, mean rank and keystrokes-to-open per
# ranking variant. Synthetic always; --real also replays the git history of
# your most active repos (reads git logs; writes nothing to your memory file).
set -euo pipefail
REPO="$(cd "$(dirname "$0")/../.." && pwd)"
cd "$REPO"
cargo build --release -p flashfind-cli 2>&1 | tail -1
OUT=bench/ux/RESULTS.md
: > "$OUT.new"
for seed in 7 11 23; do
  target/release/flashfind bench-ux --seed "$seed" --md "$OUT.new" >/dev/null
done
if [ "${1:-}" = "--real" ]; then
  target/release/flashfind bench-ux --real --md "$OUT.new" >/dev/null
fi
{ echo "# UX replay results"; echo; echo "Generated by bench/ux/run.sh on $(uname -sm), $(date -u +%Y-%m-%d)."; echo; cat "$OUT.new"; } > "$OUT"
rm -f "$OUT.new"
cat "$OUT"
