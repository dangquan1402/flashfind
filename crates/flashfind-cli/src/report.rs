//! Merge bench JSON files into bench/RESULTS.md.

use crate::Args;
use serde_json::Value;
use std::fmt::Write;

fn read(f: &str) -> Value {
    serde_json::from_str(&std::fs::read_to_string(f).unwrap_or_else(|e| crate::die(format!("{f}: {e}")))).unwrap()
}

/// Best of several runs: the one with the smallest `metric` (path a/b).
fn best(files: Vec<String>, metric: &[&str]) -> Option<Value> {
    let key = |v: &Value| metric.iter().fold(v, |v, k| &v[*k]).as_f64().unwrap_or(f64::INFINITY);
    files.iter().map(|f| read(f)).min_by(|a, b| key(a).partial_cmp(&key(b)).unwrap())
}

fn ms(v: &Value) -> String {
    v.as_f64()
        .map_or("–".into(), |x| if x >= 1000.0 { format!("{:.2} s", x / 1e3) } else { format!("{x:.0} ms") })
}
fn us(v: &Value) -> String {
    v.as_f64()
        .map_or("–".into(), |x| if x >= 1000.0 { format!("{:.2} ms", x / 1e3) } else { format!("{x:.0} µs") })
}
fn mb(v: &Value) -> String {
    v.as_f64().map_or("–".into(), |x| format!("{:.0} MB", x / 1e6))
}
fn pct(v: &Value) -> String {
    v.as_f64().map_or("–".into(), |x| format!("{:.0}%", x * 100.0))
}

pub fn run(mut a: Args) {
    let machine = a
        .opt(&["--machine"])
        .map(|f| std::fs::read_to_string(f).unwrap_or_default())
        .unwrap_or_default();
    let notes = a.opt(&["--notes"]).map(|f| std::fs::read_to_string(f).unwrap_or_default()).unwrap_or_default();
    let ffb = best(a.opts("--ff-build"), &["crawl_ms"]);
    let ffq = best(a.opts("--ff-query"), &["overall", "p50_us"]);
    let fsb = best(a.opts("--fs-build"), &["crawl_ms"]);
    let fsq = best(a.opts("--fs-query"), &["overall", "p50_us"]);
    let out = a.opt(&["--out"]).unwrap_or_else(|| "bench/RESULTS.md".into());
    let null = Value::Null;
    let g = |v: &Option<Value>, k: &str| -> Value { v.as_ref().map_or(Value::Null, |v| v[k].clone()) };
    let mut s = String::new();
    writeln!(s, "# Benchmark results\n").unwrap();
    writeln!(s, "Generated by `bench/run.sh`. Engines are measured **in-process** through their libraries (flashfind `Session::search`; fsearch `query::Searcher::search` on a `live::Live` over an index built by `walk::scan` + `Index::build` for the same root). Latency includes query parsing and turning the top 50 hits into paths. Synthetic tree, warm page cache. Each engine ran twice, alternating; the better run (lower crawl time / lower overall p50) is shown for each.\n").unwrap();
    writeln!(s, "## Machine\n\n```\n{}\n```\n", machine.trim()).unwrap();
    writeln!(s, "## Index build\n\n| metric | flashfind | fsearch |\n|---|---|---|").unwrap();
    writeln!(s, "| entries indexed | {} | {} |", g(&ffb, "entries"), g(&fsb, "entries")).unwrap();
    writeln!(s, "| crawl | {} | {} |", ms(&g(&ffb, "crawl_ms")), ms(&g(&fsb, "crawl_ms"))).unwrap();
    writeln!(s, "| index build | {} | {} |", ms(&g(&ffb, "build_ms")), ms(&g(&fsb, "build_ms"))).unwrap();
    writeln!(s, "| save | {} | {} |", ms(&g(&ffb, "save_ms")), ms(&g(&fsb, "save_ms"))).unwrap();
    writeln!(s, "| index file size | {} | {} |", mb(&g(&ffb, "index_bytes")), mb(&g(&fsb, "index_bytes"))).unwrap();
    writeln!(
        s,
        "| peak RSS while indexing | {} | {} |",
        mb(&g(&ffb, "peak_rss_bytes")),
        mb(&g(&fsb, "peak_rss_bytes"))
    )
    .unwrap();
    writeln!(
        s,
        "| index load (mmap + prefault) | {} | {} |",
        ms(&g(&ffq, "index_load_ms")),
        ms(&g(&fsq, "index_load_ms"))
    )
    .unwrap();
    writeln!(
        s,
        "| peak RSS while querying | {} | {} |\n",
        mb(&g(&ffq, "peak_rss_bytes")),
        mb(&g(&fsq, "peak_rss_bytes"))
    )
    .unwrap();
    writeln!(s, "## Query latency and accuracy\n\n`hit@1` = the generated target file is the first result (`hit@10`: in the top 10). Classes without a target measure latency only. `keys` replays typing a file name one character at a time (latency per keystroke; hit@1 after the last one).\n").unwrap();
    writeln!(s, "| class | n | flashfind p50 | p95 | p99 | fsearch p50 | p95 | p99 | flashfind hit@1 (@10) | fsearch hit@1 (@10) |\n|---|---|---|---|---|---|---|---|---|---|").unwrap();
    let mut classes: Vec<String> = Vec::new();
    for v in [&ffq, &fsq].into_iter().flatten() {
        if let Some(m) = v["classes"].as_object() {
            for k in m.keys() {
                if !classes.contains(k) {
                    classes.push(k.clone());
                }
            }
        }
    }
    let order = [
        "exact",
        "stem",
        "ext",
        "multi",
        "typo_swap",
        "typo_drop",
        "typo_insert",
        "typo_sub",
        "typo_first",
        "short1",
        "short2",
        "prefix3",
        "filter_size",
        "filter_mtime",
        "keys",
    ];
    classes.sort_by_key(|c| order.iter().position(|o| o == c).unwrap_or(99));
    for c in &classes {
        let f = ffq.as_ref().map_or(&null, |v| &v["classes"][c]);
        let o = fsq.as_ref().map_or(&null, |v| &v["classes"][c]);
        let acc = |x: &Value| {
            if x["hit1"].is_null() {
                "–".to_string()
            } else {
                format!("{} ({})", pct(&x["hit1"]), pct(&x["hit10"]))
            }
        };
        writeln!(
            s,
            "| {c} | {} | {} | {} | {} | {} | {} | {} | {} | {} |",
            f["n"],
            us(&f["p50_us"]),
            us(&f["p95_us"]),
            us(&f["p99_us"]),
            us(&o["p50_us"]),
            us(&o["p95_us"]),
            us(&o["p99_us"]),
            acc(f),
            acc(o)
        )
        .unwrap();
    }
    let f = ffq.as_ref().map_or(&null, |v| &v["overall"]);
    let o = fsq.as_ref().map_or(&null, |v| &v["overall"]);
    writeln!(
        s,
        "| **all** | {} | {} | {} | {} | {} | {} | {} | | |\n",
        f["n"],
        us(&f["p50_us"]),
        us(&f["p95_us"]),
        us(&f["p99_us"]),
        us(&o["p50_us"]),
        us(&o["p95_us"]),
        us(&o["p99_us"])
    )
    .unwrap();
    if !notes.trim().is_empty() {
        writeln!(s, "## Notes\n\n{}\n", notes.trim()).unwrap();
    }
    std::fs::write(&out, s).unwrap_or_else(|e| crate::die(e));
    eprintln!("wrote {out}");
}
